  /* ───────────────────── Markup → HTML (ปลอดภัย: escape ก่อนเสมอ) ───────────────────── */
  function inline(raw) {
    var codes = [];
    var h = esc(raw).replace(/`([^`]+)`/g, function (_, c) { codes.push(c); return '\u0000' + (codes.length - 1) + '\u0000'; });
    h = h.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>');
    h = h.replace(/\[\[([^\]]+)\]\]/g, '<span class="fcm-chip">$1</span>');
    h = h.replace(/\[([^\]]+)\]\((https?:\/\/[^\s)]+)\)/g, '<a href="$2" target="_blank" rel="noopener noreferrer">$1</a>');
    h = h.replace(/\u0000(\d+)\u0000/g, function (_, i) { return '<code>' + codes[i] + '</code>'; });
    return h;
  }
  var LIST_RE = /^(\s*)([-*]|\d+\.)\s+(.*)$/;
  function isBlockStart(ln) {
    return /^##\s/.test(ln) || LIST_RE.test(ln) || /^!?>\s?/.test(ln);
  }
  function buildList(items) {
    var html = '', stack = [];
    items.forEach(function (it, idx) {
      var tag = it.ordered ? 'ol' : 'ul';
      while (stack.length && it.indent < stack[stack.length - 1].indent) {
        html += '</li></' + stack.pop().tag + '>';
      }
      if (!stack.length || it.indent > stack[stack.length - 1].indent) {
        var start = (it.ordered && it.num > 1 && idx === 0) ? ' start="' + it.num + '"' : '';
        html += '<' + tag + start + '>';
        stack.push({ indent: it.indent, tag: tag });
      } else {
        html += '</li>';
      }
      html += '<li>' + inline(it.text).replace(/\n/g, '<br>');
    });
    while (stack.length) html += '</li></' + stack.pop().tag + '>';
    return html;
  }
  function renderBody(body) {
    var lines = String(body == null ? '' : body).replace(/\r/g, '').split('\n');
    var out = [], i = 0, m;
    while (i < lines.length) {
      var ln = lines[i];
      if (!ln.trim()) { i++; continue; }

      if ((m = /^##\s+(.*)$/.exec(ln))) { out.push('<h4>' + inline(m[1]) + '</h4>'); i++; continue; }

      if (/^!>\s?/.test(ln) || /^>\s?/.test(ln)) {
        var warn = /^!>/.test(ln), buf = [];
        var re = warn ? /^!>\s?(.*)$/ : /^>\s?(.*)$/;
        while (i < lines.length && re.test(lines[i])) { buf.push(inline(re.exec(lines[i])[1])); i++; }
        out.push('<div class="fcm-note ' + (warn ? 'warn' : 'tip') + '"><span class="fcm-note-t">' + (warn ? 'ข้อควรระวัง' : 'เคล็ดลับ') + '</span>' + buf.join('<br>') + '</div>');
        continue;
      }

      if (LIST_RE.test(ln)) {
        var items = [];
        while (i < lines.length && (m = LIST_RE.exec(lines[i]))) {
          items.push({ indent: m[1].length, ordered: /\d/.test(m[2]), num: parseInt(m[2], 10) || 1, text: m[3] });
          i++;
          while (i < lines.length && /^\s{2,}\S/.test(lines[i]) && !LIST_RE.test(lines[i])) {
            items[items.length - 1].text += '\n' + lines[i].trim(); i++;
          }
        }
        out.push(buildList(items));
        continue;
      }

      var para = [];
      while (i < lines.length && lines[i].trim() && !isBlockStart(lines[i])) { para.push(inline(lines[i].trim())); i++; }
      if (!para.length) { i++; continue; } /* กันวนไม่รู้จบ */
      out.push('<p>' + para.join('<br>') + '</p>');
    }
    return out.join('');
  }
